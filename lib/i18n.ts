export function getBrowserLanguage(serverHint?: Language): Language {
  if (typeof window === "undefined") return serverHint ?? "en";

  const languages = (
    Array.isArray(navigator.languages) && navigator.languages.length
      ? navigator.languages
      : [navigator.language]
  )
    .filter(Boolean)
    .map((l) => l.toLowerCase());

  const primary = languages[0]?.split("-")[0];
  const hasSpanish = languages.some((l) => l.startsWith("es"));

  let inSpanishTimezone = false;
  try {
    const tz = Intl.DateTimeFormat().resolvedOptions().timeZone;
    inSpanishTimezone = SPANISH_TIMEZONES.has(tz);
  } catch {}

  if (primary === "es") return "es";
  if (serverHint === "es") return "es";
  if (primary === "en") {
    if (inSpanishTimezone && hasSpanish) return "es";
    return "en";
  }
  if (inSpanishTimezone || hasSpanish) return "es";
  return serverHint ?? "en";
}
